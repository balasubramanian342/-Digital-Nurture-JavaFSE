public class OperatorPrecedence {
    public static void main(String[] args) {
       int r1=10+4*1;
       int r2=(10+4)*1; 
       int r3=10/2+4*2;
         System.out.println("Result 1: " + r1); 
         System.out.println("Result 2: " + r2);
         System.out.println("Result 3: " + r3);  
    }
}
