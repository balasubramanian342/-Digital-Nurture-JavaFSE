public class TypeCasting {
    public static void main(String[] args) {
       double d=3.14;
       int i=(int)d; 
       System.out.println("Double value: " + d);
       System.out.println("Integer value: " + i);
       int n = 50;
       double m = (double)n;
       System.out.println("Double value: " + m);
       System.out.println("Integer value: " + n);
    }
}
